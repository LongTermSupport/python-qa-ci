"""The agent summary: one standing instruction per defence, in a generated region of a file."""

from __future__ import annotations

from typing import TYPE_CHECKING

from py_qa.finding import Finding

if TYPE_CHECKING:
    from py_qa.config import Config
    from py_qa.defences import Defence
    from py_qa.record import RecordEntry

STALE = "pyqaci.summary.stale"
BEGIN = "<!-- BEGIN py-qa summary: generated by `py-qa summary`, do not edit -->"
END = "<!-- END py-qa summary -->"
# The region's markers before py-qa-ci 0.2.0, replaced in place by the first write after it.
FORMER_MARKERS = (
    "<!-- BEGIN python-qa summary: generated by `python-qa summary`, do not edit -->",
    "<!-- END python-qa summary -->",
)
_TOOL_NAMES = {"pylint": "Pylint", "py-qa": "py-qa"}


def render(defences: list[Defence], entries: list[RecordEntry], config: Config) -> str:
    """Return the region: the bespoke defences one per line, the catalogues counted."""
    lines = [
        BEGIN,
        "## Defences enforced by py-qa",
        "",
        "Run `py-qa run` before committing. `py-qa rule-doc <identifier>` prints the "
        "documentation for any identifier a finding prints, offline.",
        "",
    ]
    for defence in defences:
        if defence.tool not in _TOOL_NAMES:
            continue
        source = _TOOL_NAMES[defence.tool]
        if defence.tool != "py-qa":
            source = f"{source}, {defence.origin}"
        lines.append(
            f"- `{defence.identifier}` ({source}): {defence.summary} Docs: `{defence.doc}`"
        )
    ruff = sum(1 for defence in defences if defence.tool == "ruff")
    mypy = sum(1 for defence in defences if defence.tool == "mypy")
    exceptions = "exception" if len(entries) == 1 else "exceptions"
    lines.extend(
        [
            f"- {ruff} Ruff rules and {mypy} mypy error codes also block; `py-qa rules` "
            "lists every one.",
            f"- Never suppress a finding without an exception in the project record: "
            f"{len(entries)} {exceptions} in `{config.record.path}`, listed by "
            "`py-qa record list`.",
            END,
        ]
    )
    return "\n".join(lines)


def place(text: str, region: str) -> str:
    """Return text with its generated region replaced by region, or region appended."""
    for begin, end_marker in ((BEGIN, END), FORMER_MARKERS):
        start, end = text.find(begin), text.find(end_marker)
        if start != -1 and end > start:
            return text[:start] + region + text[end + len(end_marker) :]
    if not text:
        return region + "\n"
    return text.rstrip("\n") + "\n\n" + region + "\n"


def write_summary(config: Config, defences: list[Defence], entries: list[RecordEntry]) -> None:
    """Write the region into the configured file, creating the file if needed."""
    if config.summary_file is None:
        return
    path = config.root / config.summary_file
    text = path.read_text(encoding="utf-8") if path.is_file() else ""
    path.write_text(place(text, render(defences, entries, config)), encoding="utf-8")


def check_summary(
    config: Config, defences: list[Defence], entries: list[RecordEntry]
) -> list[Finding]:
    """Report a region that differs from what would be generated now."""
    if config.summary_file is None:
        return []
    path = config.root / config.summary_file
    text = path.read_text(encoding="utf-8") if path.is_file() else ""
    if place(text, render(defences, entries, config)) == text:
        return []
    return [
        Finding(
            config.summary_file,
            0,
            STALE,
            "the generated summary is out of date; run `py-qa summary` and commit it",
        )
    ]
